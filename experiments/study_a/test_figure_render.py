#!/usr/bin/env python3
"""Failing-first fixtures for the figure renderer."""
from __future__ import annotations

import pathlib
import sys
import tempfile

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from figure_render import (  # noqa: E402
    FigureError, build_dot, flatten_for_ocr, label_match, normalise_confusables,
    ocr_labels, readability_gate, render, strip_nondeterminism,
)

FAILURES: list[str] = []


def check(name: str, ok: bool, detail: str = "") -> None:
    print(("PASS " if ok else "FAIL ") + name + ((" :: " + detail) if not ok and detail else ""))
    if not ok:
        FAILURES.append(name)


def raises(fn, *a, **k):
    try:
        fn(*a, **k)
    except FigureError as exc:
        return str(exc)
    except Exception as exc:  # noqa: BLE001
        return f"__WRONG_TYPE__{type(exc).__name__}: {exc}"
    return "__NO_ERROR__"


SPEC = {"figure_id": "fig-test", "orientation": "landscape",
        "blocks": ["Alpha block", "Beta block", "Gamma block"],
        "edges": [["Alpha block", "Beta block"], ["Beta block", "Gamma block"]],
        "labels_exactly_as_written": ["Alpha block", "Beta block", "Gamma block"]}


def main() -> int:
    src = build_dot(SPEC)
    check("every declared block appears as a node",
          all(f'"{b}" [label="{b}"]' in src for b in SPEC["blocks"]), src)
    check("every declared edge appears once",
          src.count("->") == len(SPEC["edges"]), src)
    check("landscape orientation lays out left to right", "rankdir=LR" in src, src)
    check("portrait orientation lays out top to bottom",
          "rankdir=TB" in build_dot({**SPEC, "orientation": "square"}))
    check("no colour is emitted anywhere in the source",
          "color=black" in src and not any(c in src.lower() for c in
              ("red", "blue", "green", "#f", "yellow")), src)

    msg = raises(build_dot, {**SPEC, "blocks": []})
    check("a specification with no blocks is refused", "declares no blocks" in msg, msg)
    msg = raises(build_dot, {**SPEC, "edges": [["Alpha block", "Missing block"]]})
    check("an edge to an undeclared block is refused and named",
          "edge target" in msg and "Missing block" in msg, msg)
    msg = raises(build_dot, {**SPEC, "edges": [["Nowhere", "Beta block"]]})
    check("an edge from an undeclared block is refused and named",
          "edge source" in msg and "Nowhere" in msg, msg)

    dirty = '<?xml version="1.0"?>\n<!-- Generated by graphviz version 1.2.3 -->\n<svg>x</svg>'
    clean = strip_nondeterminism(dirty)
    check("the generator comment is stripped", "graphviz version" not in clean, clean)
    check("stripping twice changes nothing", strip_nondeterminism(clean) == clean)

    m = label_match(SPEC, "alpha block beta block gamma block")
    check("a perfect reading scores one", m["match"] == 1.0, str(m))
    m = label_match(SPEC, "alpha block beta block")
    check("a missing label lowers the score and is named",
          abs(m["match"] - 2 / 3) < 1e-9 and m["missing"] == ["Gamma block"], str(m))
    cs = {"figure_id": "c", "blocks": ["C00 baseline"], "labels_exactly_as_written": ["C00 baseline"]}
    check("a zero read as a letter O still matches",
          label_match(cs, "COO baseline")["match"] == 1.0)
    check("folding does not accept a genuinely different label",
          label_match(cs, "C11 baseline")["match"] == 0.0)
    check("folding does not accept a truncated label",
          label_match(cs, "C00 basel")["match"] == 0.0)
    check("folding is confined to visually identical glyphs",
          normalise_confusables("O0lI|") == "00111" and normalise_confusables("abc") == "abc",
          normalise_confusables("O0lI|"))

    msg = raises(label_match, {"blocks": []}, "text")
    check("a specification with no labels is refused",
          "no labels to check" in msg, msg)

    with tempfile.TemporaryDirectory() as td:
        paths = render(SPEC, pathlib.Path(td))
        check("rendering produces all three files",
              all(paths[k].is_file() for k in ("dot", "svg", "png")), str(paths))
        first = paths["svg"].read_bytes()
        paths2 = render(SPEC, pathlib.Path(td))
        check("rendering the same specification twice gives identical vector bytes",
              paths2["svg"].read_bytes() == first)
        # the renderer writes RGBA; reading it unflattened returns nothing at all,
        # which is indistinguishable from a figure containing no text
        from PIL import Image
        flat = flatten_for_ocr(paths["png"])
        check("flattening removes the alpha channel",
              Image.open(flat).mode == "L", Image.open(flat).mode)
        check("labels are recoverable after flattening",
              label_match(SPEC, ocr_labels(paths["png"]))["match"] == 1.0,
              repr(ocr_labels(paths["png"])[:120]))

        gate = readability_gate(SPEC, paths)
        check("a clean render passes the readability gate",
              gate["passed"], str(gate))
        # a coloured image must be refused, and the refusal must name colour
        try:
            from PIL import Image
            cp = pathlib.Path(td) / "coloured.png"
            Image.new("RGB", (40, 40), (200, 30, 30)).save(cp)
            cgate = readability_gate(SPEC, {**paths, "png": cp})
            check("a coloured image is refused because it is coloured",
                  not cgate["passed"] and any("colour" in f for f in cgate["failures"]),
                  str(cgate))
            check("the colour check reports that it actually ran",
                  cgate.get("colour_checked") is True, str(cgate))
        except ImportError:
            check("the colour check refuses to pass when it cannot run", False,
                  "imaging library missing; gate must not silently clear the figure")

        # force the colour check to fail: a non-image file must not be cleared
        ngate = readability_gate(SPEC, {**paths, "png": paths["dot"]})
        check("a figure that cannot be read as an image is not cleared",
              not ngate["passed"] and any("cannot be checked" in f or "could not run" in f
                                          for f in ngate["failures"]), str(ngate))
        check("an unreadable figure is never reported as colour-cleared",
              ngate.get("colour_checked") is False, str(ngate))

        # regression: a wide figure is where both bounding and flattening matter.
        # Unbounded, the reader returns nothing; unflattened, the alpha channel
        # makes it return nothing. A three-block figure hides both defects.
        wide_blocks = ["Root agent", "Context graph", "Literature retrieval",
                       "Decision protocol", "Evidence protocol", "Sandbox execution",
                       "Deterministic validator", "Manuscript synthesis"]
        WIDE = {"figure_id": "fig-wide", "orientation": "landscape",
                "blocks": wide_blocks,
                "edges": [[wide_blocks[i], wide_blocks[i + 1]] for i in range(len(wide_blocks) - 1)],
                "labels_exactly_as_written": wide_blocks}
        wpaths = render(WIDE, pathlib.Path(td))
        wgate = readability_gate(WIDE, wpaths)
        check("a wide eight-block figure is fully readable",
              wgate["label_match"] == 1.0 and wgate["passed"],
              f"match {wgate['label_match']}, missing {wgate['missing_labels']}")

        bad = readability_gate(SPEC, paths, minimum=1.01)
        check("an unreachable threshold fails the gate with its number",
              not bad["passed"] and "below the required" in bad["failures"][0], str(bad))

    print(f"\n{len(FAILURES)} failing: {', '.join(FAILURES)}" if FAILURES else "\nall checks passed")
    return 1 if FAILURES else 0


if __name__ == "__main__":
    raise SystemExit(main())
